const fs = require('node:fs');
const path = require('node:path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/**
 * Lets the app talk to a backend on the device's own loopback address over
 * plain HTTP, and nothing else.
 *
 * Android 9 (API 28) and later refuse cleartext traffic by default. The debug
 * variant opts back in wholesale, the release variant does not — which is why a
 * sideloaded release APK pointed at `http://127.0.0.1:4000` through
 * `adb reverse` boots fine but fails every request with "Network Error".
 *
 * The config written here keeps Android's default `cleartextTrafficPermitted =
 * false` for every real host and opens exactly three names:
 *
 *   127.0.0.1  the device itself, where `adb reverse` terminates
 *   localhost  the same thing by name
 *   10.0.2.2   the Android emulator's alias for the host machine
 *
 * None of those can be a real user's server, so this cannot be used to send a
 * member's traffic anywhere in the clear. It is narrower than flipping
 * `usesCleartextTraffic="true"`, which would permit plain HTTP to any host.
 *
 * The JavaScript side stays independent: `src/config/environment.ts` still
 * refuses to start a production bundle unless the origins are HTTPS or
 * `EXPO_PUBLIC_ALLOW_INSECURE_LAN=true` is set for a private host. Both guards
 * have to be satisfied for a plaintext build to run.
 */

const CONFIG_RESOURCE = 'network_security_config';

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/withLoopbackCleartext.js — do not edit by hand.
  Cleartext stays denied everywhere except the device's own loopback, which is
  where an adb-reverse tunnel to a development backend terminates.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">10.0.2.2</domain>
    </domain-config>
</network-security-config>
`;

const withNetworkSecurityConfigFile = (config) =>
  withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const directory = path.join(modConfig.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      await fs.promises.mkdir(directory, { recursive: true });
      await fs.promises.writeFile(path.join(directory, `${CONFIG_RESOURCE}.xml`), NETWORK_SECURITY_CONFIG, 'utf8');
      return modConfig;
    },
  ]);

const withNetworkSecurityConfigReference = (config) =>
  withAndroidManifest(config, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(modConfig.modResults);
    application.$['android:networkSecurityConfig'] = `@xml/${CONFIG_RESOURCE}`;
    return modConfig;
  });

module.exports = (config) => withNetworkSecurityConfigReference(withNetworkSecurityConfigFile(config));
